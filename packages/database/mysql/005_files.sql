CREATE TABLE file_folders (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  organization_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  classroom_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
  parent_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
  name VARCHAR(200) NOT NULL, created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), UNIQUE(id,organization_id),
  FOREIGN KEY(organization_id) REFERENCES organizations(id), FOREIGN KEY(classroom_id) REFERENCES classrooms(id),
  FOREIGN KEY(parent_id) REFERENCES file_folders(id), FOREIGN KEY(created_by) REFERENCES users(id),
  FOREIGN KEY(classroom_id,organization_id) REFERENCES classrooms(id,organization_id),
  FOREIGN KEY(parent_id,organization_id) REFERENCES file_folders(id,organization_id),
  CHECK(CHAR_LENGTH(name) BETWEEN 1 AND 200), CHECK(parent_id IS NULL OR parent_id<>id),
  INDEX file_folders_scope(organization_id,classroom_id,parent_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;
