CREATE TABLE files (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  organization_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  classroom_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
  folder_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
  name VARCHAR(200) NOT NULL, original_name VARCHAR(200) NOT NULL,
  object_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  byte_size BIGINT NOT NULL, sha256 VARCHAR(64) CHARACTER SET ascii,
  media_type VARCHAR(200) CHARACTER SET ascii,
  status ENUM('uploading','quarantined','ready','rejected','failed','deleting','deleted') NOT NULL,
  scan_status ENUM('pending','clean','infected','unscanned','error') NOT NULL,
  failure_code VARCHAR(100) CHARACTER SET ascii,
  uploaded_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  source_file_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin,
  delete_reason ENUM('user','infected','upload_failed','upload_expired'),
  cleanup_attempts INT NOT NULL DEFAULT 0, next_cleanup_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  scan_attempts INT NOT NULL DEFAULT 0, next_scan_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  scan_claim CHAR(36) CHARACTER SET ascii COLLATE ascii_bin, scan_claimed_until DATETIME(3),
  purpose ENUM('resource','presentation') NOT NULL DEFAULT 'resource',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE(id,organization_id), FOREIGN KEY(organization_id) REFERENCES organizations(id),
  FOREIGN KEY(classroom_id) REFERENCES classrooms(id), FOREIGN KEY(folder_id) REFERENCES file_folders(id),
  FOREIGN KEY(uploaded_by) REFERENCES users(id), FOREIGN KEY(source_file_id) REFERENCES files(id),
  FOREIGN KEY(classroom_id,organization_id) REFERENCES classrooms(id,organization_id),
  FOREIGN KEY(folder_id,organization_id) REFERENCES file_folders(id,organization_id),
  CHECK(CHAR_LENGTH(name) BETWEEN 1 AND 200), CHECK(byte_size>0),
  CHECK(sha256 IS NULL OR CHAR_LENGTH(sha256)=64), CHECK(cleanup_attempts>=0), CHECK(scan_attempts>=0),
  INDEX files_scope(organization_id,classroom_id,folder_id,created_at,id), INDEX files_cleanup(status,updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;
